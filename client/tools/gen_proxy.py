#!/usr/bin/env python3
"""Generates client/proxy/fbclient_proxy.dpr from client/proxy/exports.txt.

Each export gets a naked asm stub that logs through fbproxy.Core.Hook and
jumps to the real function, so the stack and calling convention (stdcall or
cdecl varargs such as isc_start_transaction) are untouched. A few functions
use typed Pascal wrappers to also log their output (see TYPED).

Build the variant without the Firebird 3 OO API entry point with the
conditional define NO_OO_API.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "proxy"
TYPED = {
    "isc_attach_database": "W_isc_attach_database",
    "isc_dsql_prepare": "W_isc_dsql_prepare",
    "isc_dsql_describe": "W_isc_dsql_describe",
    "isc_dsql_describe_bind": "W_isc_dsql_describe_bind",
}
OO_API = "fb_get_master_interface"


def main() -> None:
    names = [n.strip() for n in (ROOT / "exports.txt").read_text().splitlines() if n.strip()]
    out = [
        "library fbclient_proxy;",
        "",
        "{ GENERATED by client/tools/gen_proxy.py from exports.txt - do not edit.",
        "  Logging proxy for the Firebird client library (task 1.2). Win32 only.",
        "  Define NO_OO_API to build without fb_get_master_interface. }",
        "",
        "{$IFNDEF WIN32}{$MESSAGE FATAL 'Win32 only'}{$ENDIF}",
        "",
        "uses",
        "  fbhttp.IBase in '..\\src\\fbhttp.IBase.pas',",
        "  fbproxy.Core in 'fbproxy.Core.pas';",
        "",
        "",
        "const",
        f"  NAME_COUNT = {len(names)};",
        "  Names: array[0..NAME_COUNT - 1] of PAnsiChar = (",
    ]
    out += [f"    '{n}'{',' if i < len(names) - 1 else ''}" for i, n in enumerate(names)]
    out += ["  );", ""]
    for i, n in enumerate(names):
        if n in TYPED:
            continue
        out += [
            f"procedure S_{n}; assembler;",
            "asm",
            "  push esp",
            f"  push {i}",
            "  call Hook",
            "  jmp eax",
            "end;",
            "",
        ]
    out += ["exports"]
    lines = []
    for n in names:
        target = TYPED.get(n, f"S_{n}")
        line = f"  {target} name '{n}'"
        if n == OO_API:
            line = "{$IFNDEF NO_OO_API}\n" + line + ",\n{$ENDIF}"
            lines.append(("oo", line))
        else:
            lines.append(("std", line))
    std = [l for k, l in lines if k == "std"]
    oo = [l for k, l in lines if k == "oo"]
    # The conditional export goes first so the comma rules stay valid.
    out += oo
    out += [l + ("," if i < len(std) - 1 else ";") for i, l in enumerate(std)]
    out += [
        "",
        "var",
        "  NameList: TNameArray;",
        "  i: Integer;",
        "begin",
        "  SetLength(NameList, NAME_COUNT);",
        "  for i := 0 to NAME_COUNT - 1 do",
        "    NameList[i] := Names[i];",
        "  ProxyInit(NameList);",
        "end.",
        "",
    ]
    (ROOT / "fbclient_proxy.dpr").write_text("\r\n".join(out), encoding="ascii")


if __name__ == "__main__":
    main()
