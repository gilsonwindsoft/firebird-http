#!/usr/bin/env python3
"""Generates client/ws-fbclient/wsfbclient.dpr.

Implemented functions (W_* in src/fbhttp.Client.pas) are exported directly.
Every other function of the public API (tools/protos.txt, extracted from
ibase.h: name, std|VARARG, stack slots, S when the first parameter is the
status vector, return type) gets an asm stub that fills the status vector
with "not supported by ws-fbclient" and cleans the stack like the real
function. fb_get_master_interface is not exported: the Devart driver works
without it (docs/api-surface.md).
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
client = (ROOT / "src" / "fbhttp.Client.pas").read_text()
implemented = sorted(set(re.findall(r"^(?:function|procedure) W_(\w+)\(", client.split("implementation")[0], re.M)))
implemented += [n for n in ("isc_get_client_major_version", "isc_get_client_minor_version") if n not in implemented]
protos = {}
for line in (ROOT / "tools" / "protos.txt").read_text().splitlines():
    name, kind, slots, status, ret = line.split()
    protos[name] = (kind, slots, status, ret)

out = [
    "library wsfbclient;",
    "",
    "{ GENERATED by client/tools/gen_wsfbclient.py - do not edit.",
    "  ws-fbclient.dll: Firebird client API over the fbhttp gateway. Win32 only.",
    "  build.bat renames wsfbclient.dll to ws-fbclient.dll. }",
    "",
    "{$IFNDEF WIN32}{$MESSAGE FATAL 'Win32 only'}{$ENDIF}",
    "",
    "uses",
    "  fbhttp.IBase in '..\\src\\fbhttp.IBase.pas',",
    "  fbhttp.Protocol in '..\\src\\fbhttp.Protocol.pas',",
    "  fbhttp.Status in '..\\src\\fbhttp.Status.pas',",
    "  fbhttp.Handles in '..\\src\\fbhttp.Handles.pas',",
    "  fbhttp.Config in '..\\src\\fbhttp.Config.pas',",
    "  fbhttp.PrepCache in '..\\src\\fbhttp.PrepCache.pas',",
    "  fbhttp.Transport in '..\\src\\fbhttp.Transport.pas',",
    "  fbhttp.Client in '..\\src\\fbhttp.Client.pas';",
    "",
]
stubs = []
for name, (kind, slots, status, ret) in sorted(protos.items()):
    if name in implemented or kind == "?":
        continue
    n = int(slots)
    cleanup = "  ret" if kind == "VARARG" or n == 0 else f"  ret {4 * n}"
    body = ["  push dword ptr [esp+4]", "  call NotSupported"] if status == "S" else ["  xor eax, eax", "  xor edx, edx"]
    out += [f"procedure U_{name}; assembler;", "asm", *body, cleanup, "end;", ""]
    stubs.append(name)

exports = [f"  W_{n} name '{n}'" for n in implemented] + [f"  U_{n} name '{n}'" for n in stubs]
out += ["exports"] + [e + ("," if i < len(exports) - 1 else ";") for i, e in enumerate(exports)]
out += ["", "begin", "end.", ""]
(ROOT / "ws-fbclient").mkdir(exist_ok=True)
(ROOT / "ws-fbclient" / "wsfbclient.dpr").write_text("\r\n".join(out), encoding="ascii")
print(f"{len(implemented)} implemented, {len(stubs)} stubs")
missing = [n for n in implemented if n not in protos]
if missing:
    print("implemented but not in protos.txt:", missing)
